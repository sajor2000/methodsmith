#!/usr/bin/env bun
// Generates docs/guideline-sources.md from the reporting-guideline registry.
// Usage: bun run docs:guideline-sources [--check]
import { promises as fs } from "fs"
import path from "path"
import { JSON_SCHEMA, load } from "js-yaml"

type Evidence = {
  title: string
  primary_citation: string
  doi: string
  pmid: number | null
  verification_date: string
  status: string
  note?: string
  supersedes?: string
}

type Registry = {
  verification: { verified_on: string }
  evidence: Record<string, Evidence>
  guidelines: Record<string, { file: string; aliases?: string[] }>
}

const GROUPS: Array<[string, string[]]> = [
  ["Trials and protocols", ["CONSORT", "CONSORT-ADAPTIVE", "CONSORT-AI", "CONSORT-CLUSTER", "CONSORT-NOF1", "SPIRIT", "SPIRIT-AI", "TIDIER", "ROB2"]],
  ["Observational", ["STROBE", "STROBE-MR", "STREGA", "RECORD", "RECORD-PE", "TARGET", "START-RWE", "ROBINS-I"]],
  ["Prediction and AI", ["TRIPOD+AI", "TRIPOD-LLM", "DEAL", "MI-CLAIM", "CLAIM", "DECIDE-AI", "REFORMS", "CHART", "PDSQI-9", "PROBAST+AI"]],
  ["Reviews and diagnostic", ["PRISMA", "PRISMA-DTA", "PRISMA-IPD", "PRISMA-NMA", "PRISMA-P", "PRISMA-SCR", "PRISMA-S", "CHARMS", "QUADAS-3", "STARD", "STARD-AI", "AMSTAR-2"]],
  ["Other", ["ARRIVE", "CARE", "CHEERS", "COREQ", "GRAMMS", "RIGHT", "SRQR", "SQUIRE"]],
]

const REPO_BLOB = "https://github.com/sajor2000/methodsmith/blob/main"
const REGISTRY_PATH = "plugins/methodsmith/skills/method-review/references/guideline-registry.yaml"
const REFERENCES_PATH = path.posix.dirname(REGISTRY_PATH)

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim()
const pubmed = (pmid: number | string) => `[${pmid}](https://pubmed.ncbi.nlm.nih.gov/${pmid}/)`

function otherPmids(entry: Evidence): string[] {
  const ids = [...(entry.note ?? "").matchAll(/PMID (\d+)/g)].map((match) => match[1])
  return [...new Set(ids)].filter((id) => id !== String(entry.pmid))
}

export function renderGuidelineSources(registryText: string): string {
  // JSON_SCHEMA keeps dates as written instead of timezone-dependent Date objects.
  const registry = load(registryText, { schema: JSON_SCHEMA }) as Registry
  const names = Object.keys(registry.evidence)
  const grouped = GROUPS.flatMap(([, members]) => members)
  const ungrouped = names.filter((name) => !grouped.includes(name))
  const missing = grouped.filter((name) => !names.includes(name))
  if (ungrouped.length || missing.length) {
    throw new Error(`Guideline groups out of sync with registry. Ungrouped: ${ungrouped.join(", ") || "none"}; missing: ${missing.join(", ") || "none"}`)
  }

  const lines = [
    "# Guideline Sources",
    "",
    "<!-- Generated by scripts/docs/guideline-sources.ts from guideline-registry.yaml. Do not edit by hand; run `bun run docs:guideline-sources`. -->",
    "",
    `Primary sources for the ${names.length} reporting guidelines, appraisal tools, and templates that \`methodsmith\` reviews against. Every row comes from the [guideline registry](${REPO_BLOB}/${REGISTRY_PATH}); registry verification date ${registry.verification.verified_on}.`,
    "",
    "Other PMIDs are errata, explanation papers, co-publications, and related records named in the registry notes. Superseded versions are never loaded; their old names resolve to the current entry.",
  ]

  for (const [group, members] of GROUPS) {
    lines.push(
      "",
      `## ${group}`,
      "",
      "| Guideline | Primary citation | PMID | DOI | Other PMIDs | Verification | Checklist | Supersedes and aliases |",
      "|---|---|---|---|---|---|---|---|",
    )
    for (const name of members) {
      const entry = registry.evidence[name]
      const guideline = registry.guidelines[name]
      if (!guideline) throw new Error(`Registry entry ${name} has no guidelines record`)
      const aliases = guideline.aliases ?? []
      const replaced = [
        entry.supersedes ? cell(entry.supersedes) : "",
        aliases.length ? `Aliases: ${aliases.map((alias) => `\`${alias}\``).join(", ")}` : "",
      ].filter(Boolean).join("<br />")
      lines.push(`| ${[
        `**${name}**`,
        cell(entry.primary_citation),
        entry.pmid ? pubmed(entry.pmid) : "None (DOI only)",
        `[${entry.doi}](https://doi.org/${entry.doi})`,
        otherPmids(entry).map(pubmed).join(", ") || "-",
        `${entry.status}, ${entry.verification_date}`,
        `[${guideline.file}](${REPO_BLOB}/${REFERENCES_PATH}/${guideline.file})`,
        replaced || "-",
      ].join(" | ")} |`)
    }
  }

  return `${lines.join("\n")}\n`
}

if (import.meta.main) {
  const repoRoot = path.resolve(import.meta.dir, "..", "..")
  const docPath = path.join(repoRoot, "docs", "guideline-sources.md")
  const rendered = renderGuidelineSources(await fs.readFile(path.join(repoRoot, REGISTRY_PATH), "utf8"))
  if (process.argv.includes("--check")) {
    const current = await fs.readFile(docPath, "utf8").catch(() => "")
    if (current !== rendered) {
      console.error("docs/guideline-sources.md is out of date. Run: bun run docs:guideline-sources")
      process.exit(1)
    }
    console.log("docs/guideline-sources.md is up to date.")
  } else {
    await fs.writeFile(docPath, rendered)
    console.log(`Wrote ${path.relative(repoRoot, docPath)}`)
  }
}
