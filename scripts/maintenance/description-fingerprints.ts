#!/usr/bin/env bun
/**
 * Regenerate src/data/shipped-description-fingerprints.json: a short hash of
 * every frontmatter `description:` that any methodsmith skill, agent, or
 * command has shipped, read from git history. Legacy cleanup uses it as the
 * second ownership signal for files from installs that predate the install
 * ledger, so an old plugin file is recognized even after its description was
 * reworded, while a user's own same-named file is not.
 *
 *   bun run scripts/maintenance/description-fingerprints.ts          # write
 *   bun run scripts/maintenance/description-fingerprints.ts --check  # verify
 */
import { readFileSync, writeFileSync } from "fs"
import path from "path"
import { parseFrontmatter } from "../../src/utils/frontmatter"
import { descriptionFingerprint } from "../../src/utils/legacy-cleanup"

const repoRoot = path.join(import.meta.dir, "..", "..")
const outputPath = path.join(repoRoot, "src", "data", "shipped-description-fingerprints.json")
const pathspecs = [
  "plugins/methodsmith/skills/*/SKILL.md",
  "plugins/methodsmith/agents/*.md",
  "plugins/methodsmith/agents/*/*.md",
  "plugins/methodsmith/commands/*.md",
  "plugins/methodsmith/commands/*/*.md",
  // Releases before 5.0 shipped from the pre-rebrand plugin folder.
  "plugins/ce-datascience/skills/*/SKILL.md", // rebrand:keep
  "plugins/ce-datascience/agents/*.md", // rebrand:keep
  "plugins/ce-datascience/agents/*/*.md", // rebrand:keep
  "plugins/ce-datascience/commands/*.md", // rebrand:keep
  "plugins/ce-datascience/commands/*/*.md", // rebrand:keep
]

function git(args: string[], input?: string): Buffer {
  const result = Bun.spawnSync(["git", ...args], { cwd: repoRoot, stdin: input ? Buffer.from(input) : undefined })
  if (result.exitCode !== 0) throw new Error(`git ${args.join(" ")} failed: ${result.stderr.toString()}`)
  return result.stdout
}

function readDescription(raw: string): string | null {
  try {
    const { data } = parseFrontmatter(raw, "history")
    if (typeof data.description === "string") return data.description
  } catch {
    // Older files may have frontmatter the current parser rejects.
  }
  const match = raw.match(/^description:\s*(.+)$/m)
  if (!match) return null
  return match[1].trim().replace(/^["']|["']$/g, "")
}

export function collectFingerprints(): string[] {
  const log = git(["log", "--all", "--format=COMMIT %H", "--name-only", "--diff-filter=AMR", "--", ...pathspecs]).toString()
  const requests: string[] = []
  let commit = ""
  for (const line of log.split("\n")) {
    if (line.startsWith("COMMIT ")) commit = line.slice(7)
    else if (line.trim()) requests.push(`${commit}:${line.trim()}`)
  }

  const fingerprints = new Set<string>()
  const batch = git(["cat-file", "--batch"], requests.join("\n") + "\n")
  let offset = 0
  while (offset < batch.length) {
    const headerEnd = batch.indexOf(10, offset)
    const header = batch.subarray(offset, headerEnd).toString()
    offset = headerEnd + 1
    const size = Number(header.split(" ")[2])
    if (header.endsWith("missing") || Number.isNaN(size)) continue
    const description = readDescription(batch.subarray(offset, offset + size).toString("utf8"))
    offset += size + 1
    if (description) fingerprints.add(descriptionFingerprint(description))
  }
  // Include the candidate release before it is committed, including new skills.
  const currentPaths = git(["ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", ...pathspecs])
    .toString().split("\0").filter(Boolean)
  for (const relative of new Set(currentPaths)) {
    try {
      const description = readDescription(readFileSync(path.join(repoRoot, relative), "utf8"))
      if (description) fingerprints.add(descriptionFingerprint(description))
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error
      // A tracked deletion remains represented by its historical fingerprint.
    }
  }
  return [...fingerprints].sort()
}

if (import.meta.main) {
  const fingerprints = collectFingerprints()
  const content = JSON.stringify(
    {
      comment: "Generated by scripts/maintenance/description-fingerprints.ts. Do not edit by hand.",
      fingerprints,
    },
    null,
    2,
  ) + "\n"
  if (process.argv.includes("--check")) {
    const current = readFileSync(outputPath, "utf8")
    const known = new Set((JSON.parse(current) as { fingerprints: string[] }).fingerprints)
    const missing = fingerprints.filter((value) => !known.has(value))
    if (missing.length > 0) {
      console.error(`${missing.length} shipped description(s) are missing; run this script without --check.`)
      process.exit(1)
    }
    console.log(`All ${fingerprints.length} shipped descriptions are fingerprinted.`)
  } else {
    writeFileSync(outputPath, content)
    console.log(`Wrote ${fingerprints.length} fingerprints to ${path.relative(repoRoot, outputPath)}`)
  }
}
